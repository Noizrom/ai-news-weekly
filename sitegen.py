"""Static site generator: digests/*.md → site/ (deployed to GitHub Pages)."""
from __future__ import annotations

import logging
import re

import markdown
import yaml

log = logging.getLogger("site")

MD_EXTENSIONS = ["extra", "sane_lists"]

_CSS = """
:root{--bg:#fafafa;--fg:#1a1a1a;--muted:#6b7280;--link:#0969da;
--card:#ffffff;--border:#e5e7eb}
@media(prefers-color-scheme:dark){:root{--bg:#0d1117;--fg:#e6edf3;
--muted:#8b949e;--link:#58a6ff;--card:#161b22;--border:#30363d}}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--fg);
font:16px/1.65 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif}
main{max-width:780px;margin:0 auto;padding:2rem 1.25rem 4rem}
h1{font-size:1.7rem;margin:.2rem 0} h2{font-size:1.15rem;margin-top:2rem;
padding-bottom:.3rem;border-bottom:1px solid var(--border)}
a{color:var(--link);text-decoration:none} a:hover{text-decoration:underline}
.meta{color:var(--muted);font-size:.92rem}
ul{padding-left:1.3rem} li{margin:.5rem 0}
nav.weeks{background:var(--card);border:1px solid var(--border);
border-radius:10px;padding:1rem 1.25rem;margin:1.5rem 0}
nav.weeks a{display:inline-block;margin:.15rem .75rem .15rem 0;font-weight:600}
hr{border:none;border-top:1px solid var(--border);margin:2.5rem 0}
footer{color:var(--muted);font-size:.85rem;margin-top:3rem;text-align:center}
"""

_SHELL = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>{css}</style>
</head>
<body>
<main>
<header><h1>{title}</h1>
<p class="meta">Auto-generated weekly AI news digest · updated {updated}</p></header>
{body}
<footer>Generated by ai-news-weekly · sources in <a href="{repo}">GitHub</a></footer>
</main>
</body>
</html>
"""


def _convert(md_text: str) -> str:
    return markdown.markdown(md_text, extensions=MD_EXTENSIONS)


def build(root, cfg: dict) -> int:
    """Render every digest into site/. Returns number of weeks published."""
    site_title = cfg.get("site", {}).get("title", "AI News Weekly")
    digests_dir, site_dir = root / "digests", root / "site"
    site_dir.mkdir(exist_ok=True)

    files = sorted(digests_dir.glob("*.md"), reverse=True)
    if not files:
        log.warning("no digests found — site not built")
        return 0

    repo_url = _repo_web_url(root)

    def shell(body: str, page_title: str) -> str:
        from datetime import datetime, timezone

        return _SHELL.format(
            title=page_title,
            css=_CSS.replace("\n", ""),
            body=body,
            updated=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            repo=repo_url,
        )

    weeks = [f.stem for f in files]
    nav = '<nav class="weeks"><strong>Browse:</strong> ' + " ".join(
        f'<a href="{w}.html">{w}</a>' for w in weeks
    ) + "</nav>"

    latest_html = _convert(files[0].read_text())
    (site_dir / "index.html").write_text(
        shell(nav + "<hr>" + latest_html, f"{site_title} — {weeks[0]}")
    )
    for path in files:
        (site_dir / f"{path.stem}.html").write_text(
            shell(nav + "<hr>" + _convert(path.read_text()),
                  f"{site_title} — {path.stem}")
        )

    log.info("site built: %d week(s) → %s", len(files), site_dir)
    return len(files)


def _repo_web_url(root) -> str:
    try:
        import subprocess

        remote = subprocess.run(
            ["git", "remote", "get-url", "origin"],
            cwd=root, capture_output=True, text=True, check=True,
        ).stdout.strip()
        m = re.match(r"(?:https://github\.com/|git@github\.com:)(.+?)(?:\.git)?$", remote)
        if m:
            return f"https://github.com/{m.group(1)}"
    except Exception:  # noqa: BLE001 — cosmetic footer link only
        pass
    return "#"
